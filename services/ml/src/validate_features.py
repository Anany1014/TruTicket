# ── Main validation runner ────────────────────────────────────────────────────

def run_validation(
    df_train:    pd.DataFrame,
    df_test:     pd.DataFrame,
    df_phase2:   pd.DataFrame,
    report_path: Path,
) -> Dict:
    """
    Run all checks and write a Markdown report.
    Returns a dict of summary statistics for programmatic inspection.
    """
    report_path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    summary = {}

    _h1(lines, "TruTicket Feature Engineering — Data Quality Report")
    lines.append("> Auto-generated by validate_features.py\n")

    # ── Phase 1 Train ────────────────────────────────────────────────────────
    _h2(lines, "Phase 1 — Training Set")
    s1 = _validate_df(df_train, "Phase 1 TRAIN", lines)
    summary["phase1_train"] = s1

    # ── Phase 1 Test ─────────────────────────────────────────────────────────
    _h2(lines, "Phase 1 — Test Set")
    s2 = _validate_df(df_test, "Phase 1 TEST", lines)
    summary["phase1_test"] = s2

    # ── Phase 1 Leakage check ────────────────────────────────────────────────
    _h2(lines, "Phase 1 — Train/Test Leakage Check")
    _leakage_check(df_train, df_test, lines, summary, "phase1")

    # ── Phase 2 ──────────────────────────────────────────────────────────────
    _h2(lines, "Phase 2 — Full Dataset (Unsplit)")
    s3 = _validate_df(df_phase2, "Phase 2 ALL", lines)
    summary["phase2_all"] = s3

    # ── Feature coverage comparison ───────────────────────────────────────────
    _h2(lines, "Feature Coverage Summary")
    _feature_coverage_table(
        {"P1 Train": df_train, "P1 Test": df_test, "P2 All": df_phase2},
        lines,
    )

    # ── Sanity checks ────────────────────────────────────────────────────────
    _h2(lines, "Feature Range Sanity Checks")
    for tag, df in [("P1 Train", df_train), ("P1 Test", df_test), ("P2 All", df_phase2)]:
        _range_checks(df, tag, lines)

    # ── Speed reliability ────────────────────────────────────────────────────
    _h2(lines, "Mouse Speed Reliability")
    for tag, df in [("P1 Train", df_train), ("P1 Test", df_test), ("P2 All", df_phase2)]:
        _speed_reliability(df, tag, lines)

    # ── Write report ─────────────────────────────────────────────────────────
    report_text = "\n".join(lines)
    with open(report_path, "w", encoding="utf-8") as fh:
        fh.write(report_text)
    logger.info("Validation report written to %s", report_path)

    return summary


# ── Per-DataFrame checks ──────────────────────────────────────────────────────

def _validate_df(df: pd.DataFrame, tag: str, lines: list) -> Dict:
    summary: Dict = {}

    if df.empty:
        lines.append(f"**{tag}**: DataFrame is empty!\n")
        return summary

    n_rows, n_cols = df.shape
    summary["rows"] = n_rows

    _h3(lines, f"{tag}: Basic Info")
    lines.append(f"- **Rows**: {n_rows}")
    lines.append(f"- **Columns**: {n_cols}")

    # Label distribution
    _h3(lines, f"{tag}: Label Distribution")
    dist = df["label"].value_counts()
    summary["label_dist"] = dist.to_dict()
    rows_md = ["| Label | Count | % |", "|-------|-------|---|"]
    for lbl, cnt in dist.items():
        pct = 100 * cnt / n_rows
        rows_md.append(f"| {lbl} | {cnt} | {pct:.1f}% |")
    lines.extend(rows_md)
    lines.append("")

    # Binary label
    bin_dist = df["binary_label"].value_counts()
    summary["binary_dist"] = bin_dist.to_dict()
    lines.append(
        f"Binary (0=human, 1=bot): "
        f"{bin_dist.get(0, 0)} human / {bin_dist.get(1, 0)} bot"
    )
    lines.append("")

    # Duplicate session check
    _h3(lines, f"{tag}: Duplicate Session IDs")
    dup_count = df["session_id"].duplicated().sum()
    summary["duplicate_session_ids"] = int(dup_count)
    if dup_count == 0:
        lines.append("✅ No duplicate session_ids found.")
    else:
        lines.append(f"⚠️ **{dup_count} duplicate session_id(s) detected!**")
        dupes = df[df["session_id"].duplicated(keep=False)]["session_id"].unique()
        lines.append(f"  Affected IDs (first 5): {list(dupes[:5])}")
    lines.append("")

    # Mouse data presence
    _h3(lines, f"{tag}: Data Presence Flags")
    mouse_pct = 100 * df["mouse_has_data"].mean()
    log_pct   = 100 * df["log_has_data"].mean()
    summary["mouse_data_pct"] = round(mouse_pct, 1)
    summary["log_data_pct"]   = round(log_pct, 1)
    lines.append(f"- Sessions with mouse data: {mouse_pct:.1f}%")
    lines.append(f"- Sessions with web log data: {log_pct:.1f}%")
    lines.append("")

    # Missing values
    _h3(lines, f"{tag}: Missing Values (NaN) per Feature")
    feat_cols = [c for c in df.columns if c.startswith("mouse_") or c.startswith("log_")
                 or c.startswith("vp_") or c.startswith("nav_")]
    if feat_cols:
        nan_counts = df[feat_cols].isna().sum()
        nan_pct    = 100 * df[feat_cols].isna().mean()
        nan_df     = pd.DataFrame({
            "NaN Count": nan_counts,
            "NaN %": nan_pct.round(1),
        })
        nan_df = nan_df[nan_df["NaN Count"] > 0].sort_values("NaN Count", ascending=False)
        summary["nan_features"] = int((nan_counts > 0).sum())
        if nan_df.empty:
            lines.append("✅ No NaN values in any feature column.")
        else:
            lines.append(f"Features with NaN values: {len(nan_df)}")
            lines.append("")
            lines.append("| Feature | NaN Count | NaN % |")
            lines.append("|---------|-----------|-------|")
            for feat, row in nan_df.iterrows():
                lines.append(f"| {feat} | {int(row['NaN Count'])} | {row['NaN %']}% |")
        lines.append("")
    else:
        lines.append("No feature columns found.")
        lines.append("")

    return summary


# ── Leakage check ─────────────────────────────────────────────────────────────

def _leakage_check(
    df_train: pd.DataFrame,
    df_test:  pd.DataFrame,
    lines:    list,
    summary:  Dict,
    tag:      str,
) -> None:
    if df_train.empty or df_test.empty:
        lines.append("Cannot check leakage — one or both DataFrames are empty.")
        return

    train_ids = set(df_train["session_id"])
    test_ids  = set(df_test["session_id"])
    overlap   = train_ids & test_ids
    summary[f"{tag}_leakage_count"] = len(overlap)

    if not overlap:
        lines.append("✅ Zero session_id overlap between train and test sets.")
    else:
        lines.append(f"🚨 **LEAKAGE DETECTED: {len(overlap)} session(s) in both train AND test!**")
        lines.append(f"  Overlapping IDs: {sorted(overlap)[:10]}")
    lines.append("")


# ── Feature coverage table ────────────────────────────────────────────────────

def _feature_coverage_table(dfs: Dict[str, pd.DataFrame], lines: list) -> None:
    all_feat_cols = set()
    for df in dfs.values():
        all_feat_cols.update(
            c for c in df.columns
            if c.startswith(("mouse_", "log_", "vp_", "nav_"))
        )
    all_feat_cols = sorted(all_feat_cols)

    header = "| Feature | " + " | ".join(dfs.keys()) + " |"
    sep    = "|---------|" + "|".join(["------"] * len(dfs)) + "|"
    lines.append(header)
    lines.append(sep)
    for fc in all_feat_cols:
        row_parts = []
        for tag, df in dfs.items():
            if fc not in df.columns:
                row_parts.append("—")
            else:
                nan_pct = 100 * df[fc].isna().mean()
                if nan_pct == 0:
                    row_parts.append("✅")
                elif nan_pct == 100:
                    row_parts.append("❌ all NaN")
                else:
                    row_parts.append(f"⚠️ {nan_pct:.0f}% NaN")
        lines.append(f"| `{fc}` | " + " | ".join(row_parts) + " |")
    lines.append("")


# ── Sanity checks ─────────────────────────────────────────────────────────────

def _range_checks(df: pd.DataFrame, tag: str, lines: list) -> None:
    if df.empty:
        return

    _h3(lines, f"{tag}: Range Checks")
    issues = []

    def _check_bounded(col: str, lo: float, hi: float, label: str) -> None:
        if col not in df.columns:
            return
        vals = df[col].dropna()
        bad  = ((vals < lo) | (vals > hi)).sum()
        if bad > 0:
            issues.append(f"⚠️ `{col}` ({label}): {bad} value(s) outside [{lo}, {hi}]")

    def _check_non_negative(col: str) -> None:
        if col not in df.columns:
            return
        vals = df[col].dropna()
        bad  = (vals < 0).sum()
        if bad > 0:
            issues.append(f"⚠️ `{col}`: {bad} negative value(s)")

    _check_bounded("mouse_straightness",        0.0, 1.0, "ratio")
    _check_bounded("mouse_click_to_move",        0.0, 1e4, "ratio, unbounded above 1 possible")
    _check_bounded("log_http10_ratio",           0.0, 1.0, "ratio")
    _check_bounded("log_content_revisit_ratio",  0.0, 1.0, "ratio")
    _check_bounded("nav_repetition_ratio",       0.0, 1.0, "ratio")

    for col in ["mouse_total_moves", "mouse_total_clicks", "log_total_requests",
                "log_session_duration_s", "mouse_total_path_px"]:
        _check_non_negative(col)

    if issues:
        lines.extend(issues)
    else:
        lines.append("✅ All range checks passed.")
    lines.append("")


def _speed_reliability(df: pd.DataFrame, tag: str, lines: list) -> None:
    if df.empty or "mouse_speed_reliable" not in df.columns:
        return
    _h3(lines, f"{tag}: Speed Reliability")
    reliable    = df["mouse_speed_reliable"].sum()
    not_reliable = (df["mouse_speed_reliable"] == 0).sum()
    has_data    = df["mouse_has_data"].sum()
    lines.append(
        f"- Sessions with mouse data: **{int(has_data)}**"
    )
    lines.append(
        f"- Speed computable (timestamps aligned): **{int(reliable)}**"
    )
    lines.append(
        f"- Speed NOT computable (NaN): **{int(not_reliable)}**"
    )
    # Verify: speed columns are NaN when not reliable
    if "mouse_speed_mean_px_s" in df.columns:
        should_be_nan = df[df["mouse_speed_reliable"] == 0]["mouse_speed_mean_px_s"]
        actual_nan    = should_be_nan.isna().all()
        if actual_nan:
            lines.append("✅ Speed features are NaN when not reliable — consistent.")
        else:
            lines.append(
                "⚠️ Some speed values are NOT NaN even though speed_reliable == 0."
            )
    lines.append("")


