"""
validate_features.py
====================
Data-quality and sanity checks for the generated feature DataFrames.

Checks performed
----------------
1.  Row counts and label distributions (each phase, each split).
2.  Missing value counts and percentages per feature column.
3.  Duplicate session_id detection.
4.  Sub-session leakage check (Phase 2): verifies that the same base
    session_id does not appear in both a train and test split.
5.  Feature range sanity (straightness 0-1, ratios 0-1, non-negative counts).
6.  Speed-reliable vs NaN speed value consistency.
7.  Mouse-data presence vs zero-move-event consistency.
8.  Produces a Markdown report saved to reports/.

Usage
-----
Run directly:
    python validate_features.py

Or import and call:
    from validate_features import run_validation
    run_validation(df_train, df_test, df_phase2, report_path)
"""

